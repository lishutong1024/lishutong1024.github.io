<h2 id="第一步-熟悉一种rtos" tabindex="-1"><a class="header-anchor" href="#第一步-熟悉一种rtos"><span>第一步：熟悉一种RTOS</span></a></h2>
<p><strong>理解RTOS的第一步，是先熟悉怎么用一种RTOS，从而搞清楚RTOS是什么。</strong></p>
<p>如果连任务、延时和线程间通信都还不能熟练使用，就直接阅读内核源码，往往很容易陷入宏定义和细节中。因此，应当选一款主流的RTOS，在实际工程中把它用起来。</p>
<p><strong>用熟RTOS的目的不是成为API使用专家</strong>，而是先在真实项目中遇到问题，建立对任务调度和任务间通信的直观认识，为后续理解内核原理做好准备。</p>
<h2 id="第二步-带着问题阅读内核源码" tabindex="-1"><a class="header-anchor" href="#第二步-带着问题阅读内核源码"><span>第二步：带着问题阅读内核源码</span></a></h2>
<p>在知道RTOS是什么之后，就可以尝试开始阅读源码，深入了解其内部工作机制。</p>
<p>不过，不建议从main()函数开始，一行一行地往下追。<strong>更有效的方式是提出一个具体问题，然后沿着相关数据结构和函数调用逐步追踪，弄清楚系统实际做了什么</strong>。</p>
<p>比如，可以优先研究以下三个问题：</p>
<ol>
<li><strong>调度器怎样决定下一个运行的任务？</strong> 可以先找到任务控制块、就绪队列，再分析选择下一个任务的核心逻辑，从而理解内核如何判断哪些任务当前可以运行，以及如何根据优先级和调度策略作出选择。</li>
<li><strong>任务切换究竟发生了什么？</strong> 从芯片的定时器中断或其他触发调度的事件入手，追踪上下文保存、调度器选择任务和上下文恢复的过程。</li>
<li><strong>任务为什么会阻塞，又是怎样被唤醒的？</strong> 观察任务等待延时、信号量或消息队列时，内核如何改变任务状态、将任务挂入相应的等待结构，以及事件发生后如何让任务重新具备运行资格。</li>
</ol>
<h2 id="第三步-手写一个最小内核" tabindex="-1"><a class="header-anchor" href="#第三步-手写一个最小内核"><span>第三步：手写一个最小内核</span></a></h2>
<p>虽然阅读源码能够帮助我们理解RTOS的实现，<strong>但更好的做法是手写一个内核</strong>。</p>
<p>通过这个过程，可以迫使我们深入理解更多问题，比如：任务控制块需要保存什么，任务切换时哪些寄存器必须保存，延时任务如何管理等？只有自己实现过，才能更清楚地理解每个机制解决了什么问题，以及设计中有哪些取舍。</p>
<p>在所有这些问题中，最难的莫过于理解：RTOS是怎么实现任务切换的？</p>
<p>对于这个问题，我之前专门做过一期视频课程《RTOS任务切换机制详解》，将其中的原理和工作机制掰开、揉碎讲。整个课程只有10余节课程，代码行数约100行左右。</p>
<p><img src="@source/notes/tech/rtos100/base/images/q07/p2.png" alt="p2.png"></p>
<p>如果你能顺利地将这些视频内容看完，相信可以对RTOS的任务切换机制有非常好的理解。你也可以继续在此基础之上开发新的功能。</p>
<h2 id="第四步-尝试跨cpu架构移植" tabindex="-1"><a class="header-anchor" href="#第四步-尝试跨cpu架构移植"><span>第四步：尝试跨CPU架构移植</span></a></h2>
<p>当一个最小内核稳定运行后，可以尝试把它移植到另一种CPU架构，例如从ARM Cortex-M移植到RISC-V。这一步能够<strong>检验内核设计是否真正区分了通用机制与硬件相关机制</strong>。</p>
<p>如果移植时发现任务调度、链表管理和架构相关的寄存器操作混杂在一起，就可以借这个机会优化实现。</p>
<p>这个过程不仅是在验证代码的可移植性，也是在检验自己对操作系统分层设计的理解。</p>
<h2 id="第五步-用自己写的内核完成一个实际项目" tabindex="-1"><a class="header-anchor" href="#第五步-用自己写的内核完成一个实际项目"><span>第五步：用自己写的内核完成一个实际项目</span></a></h2>
<p>最后，可以将内核放进一个实际项目中。</p>
<p>当我们在单独测试RTOS的某个功能模块时，很多问题并不容易暴露；只有在真正的实际多任务环境中，任务之间的竞争关系才会真正显现出来，一些隐藏的问题才会显现。</p>
<p>例如，可以实现一个远程温湿度监控设备：一个任务周期性采集传感器数据，一个任务负责将数据写入SD卡文件系统，另一个任务通过LwIP上传数据，最后由HTTP服务提供远程查看功能。这个项目会带来一系列需要权衡的问题：</p>
<ul>
<li>任务优先级如何安排？</li>
<li>每个任务需要多少栈空间？</li>
<li>哪些共享资源需要互斥保护？</li>
<li>临界区应该如何设计？</li>
<li>内存分配和网络缓冲区如何管理？</li>
</ul>
<p>这些问题没有一个适用于所有项目的固定答案，而是需要结合实时性要求、硬件资源和具体RTOS实现进行分析。</p>
<p>可以看到，通过实际项目，我们才能验证自己写的内核不仅能”跑多任务”，而且能在真实环境下稳定工作。</p>

<h2 id="决定谁先被调度" tabindex="-1"><a class="header-anchor" href="#决定谁先被调度"><span>决定谁先被调度</span></a></h2>
<p>在RTOS中，调度器的核心职责是：从所有就绪任务里挑出某个任务来运行。</p>
<p><strong>通常情况下，采用基于优先级的策略：优先选择就绪队列中优先级最高的那一个任务。</strong></p>
<p>需要说明的是，在很多RTOS中，优先级的数值越小，代表优先级越高。</p>
<p>因此，当多个任务都处于就绪态时，谁的优先级更高，谁就能先得到运行的机会，优先级较高的任务只能排队等待。</p>
<p><img src="@source/notes/tech/rtos100/task/images/q15/就绪队列优先级调度流程图.jpg" alt="就绪队列优先级调度流程图"></p>
<p>（注：本文示例中，优先级数据越小，代表优先级越高。例中，0的优先级最高，1次之。。。。）</p>
<p>例如，在上图中，任务A、B、C都在就绪队列中，优先级分别为5、2、8，其中任务B的数值最小、优先级最高，因此会被调度器优先选中、获得CPU。</p>
<h2 id="决定谁能抢占谁" tabindex="-1"><a class="header-anchor" href="#决定谁能抢占谁"><span>决定谁能抢占谁</span></a></h2>
<p>除了运行的先后顺序外，<strong>RTOS还支持按优先级来决定是否抢占一个任务</strong>。</p>
<p>例如，当低优先级任务正在运行时，高优先级任务因为某个事件，比如中断触发等而突然就绪，调度器会立刻暂停运行当前低优先级任务，将CPU切换至高优先级任务运行。</p>
<p><img src="@source/notes/tech/rtos100/task/images/q15/高优先级抢占低优先级时序图.jpg" alt="高优先级抢占低优先级时序图"></p>
<p>这意味着，<strong>只要任务的优先级足够高，在它需要运行的时候就能“插队”运行</strong>。如此一来，它能得到的响应延迟也就越有保障。</p>
<h2 id="决定谁先获得资源" tabindex="-1"><a class="header-anchor" href="#决定谁先获得资源"><span>决定谁先获得资源</span></a></h2>
<p>优先级的作用其实不止于调度。</p>
<p>在很多RTOS中，信号量、消息队列等内部实现中，<strong>其内部的等待队列支持按照任务的优先级进行排序</strong>。当多个任务同时排队等待时，一旦资源可用，等待队列中优先级最高的任务会最先被唤醒、拿到资源。</p>
<p>也就是说，<strong>优先级不仅决定了谁先抢到CPU，还决定了谁先抢到共享资源</strong>。
<img src="@source/notes/tech/rtos100/task/images/q15/等待队列按优先级唤醒流程图.jpg" alt="等待队列按优先级唤醒流程图"></p>
<p>例如，在上图中，任务B的优先级最高；当资源可用时，任务B会最先被唤醒、获得该资源。</p>
<h2 id="总结" tabindex="-1"><a class="header-anchor" href="#总结"><span>总结</span></a></h2>
<p>实际上，<strong>任务优先级本质上是一套&quot;谁更紧急，谁先得到资源&quot;的排序规则。这种资源可以是CPU运行机会，也可以是信号量、消息资源。</strong></p>
<p>它既决定了多个任务就绪时谁先被调度，也决定了高优先级任务能否立即抢占低优先级任务。同时，在等待共享资源时，还能决定谁先被唤醒。</p>

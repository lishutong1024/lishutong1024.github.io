<p>有关RTOS中的“优先级反转”现像，经常被引用的一个例子如下：</p>
<blockquote>
<p>1997年，NASA的火星探路者号探测器在火星执行任务时，出现了周期性系统重启。
排查后发现是由于优先级反现像转导致的。</p>
<p>这种现像导致系统中某个高优先级任务迟迟无法运行。而看门狗定时器监控的正是这个高优先级任务的执行状态，由于任务被阻塞后无法按时完成工作，导致看门狗检测到超时后触发了系统重启。</p>
</blockquote>
<p>那么，什么是优先级反转？它有什么问题？这种危害一定要加以解决吗？在这篇文章中，我将详细对这些问题加以解答。</p>
<h2 id="什么是优先级反转" tabindex="-1"><a class="header-anchor" href="#什么是优先级反转"><span>什么是优先级反转</span></a></h2>
<p>要理解什么是优先级反转，需要先理解该现像的发生过程。</p>
<p>在如下图所示的示例中，共包含三个任务：高优先级任务H、中优先级任务M、低优先级任务L。其中，H和L均通过互斥锁对同一共享资源进行访问。
<img src="@source/notes/tech/rtos100/schedule/images/q37/优先级反转发生过程时序图.jpg" alt="优先级反转发生过程时序图"></p>
<p>整个过程分别介绍如下：</p>
<ol>
<li><strong>L获取锁</strong>：L先获取互斥锁，开始访问共享资源。</li>
<li><strong>H阻塞等待</strong>：H开始运行，也需要访问共享资源，但锁已经被L持有，H只能阻塞等待。</li>
<li><strong>M抢占L</strong>：M变为就绪态。由于M的优先级比L高，M抢占L开始运行。</li>
<li><strong>L释放锁</strong>：当M运行完毕后，被抢占的L恢复运行，继续访问共享资源，之后释放锁。</li>
<li><strong>H获取锁</strong>：H获取互斥锁，开始访问共享资源。</li>
</ol>
<p>关键问题在于第3步：<strong>由于L被M抢占后，在M运行的整个期间，H因为无法获取锁而无法运行。</strong> 结果就是，<strong>优先级最高的H，反而因为M的运行而长时间得不到执行</strong>。</p>
<p>这<strong>就好像H的优先级被&quot;反转&quot;了，变成了比M还低，这种现像叫做优先级反转。</strong></p>
<h2 id="优先级反转带来的问题" tabindex="-1"><a class="header-anchor" href="#优先级反转带来的问题"><span>优先级反转带来的问题</span></a></h2>
<p>读到这里，你可能会有一个疑问：<strong>H由于等信锁而暂停运行，这不是很合理的现像吗？这种现像有什么问题呢？</strong></p>
<p>问题的关键在于等待的时间。如果没有优先级反转（假设没有M），那么高优先级任务H只需要等低优先级任务L执行完临界区，<strong>等待时间就是L的临界区长度，该长度是可控且可预测的</strong>。</p>
<p>例如，在图中，L执行临界区的时间是100us，那么H等待的时间也是100us。
<img src="@source/notes/tech/rtos100/schedule/images/q37/无中优先级任务时锁等待时序图.jpg" alt="无中优先级任务时锁等待时序图"></p>
<p>当发生优先级反转时，M抢占了L，导致L无法继续执行也无法释放锁，<strong>H的等待时间被M的运行时间拉长，变得不可控</strong>。而M可能只运行几毫秒，也可能运行几百毫秒，此时H的响应时间受此影响，变得无法预测。
<img src="@source/notes/tech/rtos100/schedule/images/q37/优先级反转下等待时间不可控时序图.jpg" alt="优先级反转下等待时间不可控时序图"></p>
<p>这样便体现出了优先级反转的问题：</p>
<blockquote>
<p>高优先级任务本来只需要等低优先级任务执行完临界区，等待时间有明确的上限。
但因为中优先级任务的存在，高优先级任务的实际等待时间被中优先级任务影响，等待时间不可预测，就好像它的优先级变得比中优先级任务还低。</p>
</blockquote>
<h2 id="优先级反转问题要不要解决" tabindex="-1"><a class="header-anchor" href="#优先级反转问题要不要解决"><span>优先级反转问题要不要解决</span></a></h2>
<p>你可能会问：这个问题严重吗？是不是所有系统都需要解决它？</p>
<p>其实，<strong>在很多对实时性要求不高的场合，优先级反转的影响不大</strong>。例如，在一个智能家居设备中，高优先级的按键处理任务因为优先级反转多等了几十毫秒，用户其实根本感觉不到，也不会造成什么后果。</p>
<p>不过，<strong>在对实时性要求严格的系统中，这种不可控的延迟就可能造成严重后果</strong>。这类系统里，高优先级任务都有明确的截止时间。例如，在汽车电子里，高优先级的刹车控制任务如果被不可控地延迟，可能导致刹车不及时，此时它是一个必须解决的问题。</p>
<p>所以，<strong>优先级反转到底要不要解决，取决于系统对高优先级任务的响应时间是否有严格要求</strong>。</p>
<h2 id="总结" tabindex="-1"><a class="header-anchor" href="#总结"><span>总结</span></a></h2>
<p>综上所述，优先级反转的原因是：</p>
<blockquote>
<p>高优先级任务因为等待低优先级任务持有的锁，而被中优先级任务间接阻塞的现象。</p>
</blockquote>
<p>这种现像将高优先级任务&quot;拉低&quot;到了和低优先级任务一样的水平，最终导致高优先级任务的响应时间被不可控地拉长。</p>

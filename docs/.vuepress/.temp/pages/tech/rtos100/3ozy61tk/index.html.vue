<h2 id="手写rtos不是为了造轮子" tabindex="-1"><a class="header-anchor" href="#手写rtos不是为了造轮子"><span>手写RTOS不是为了造轮子</span></a></h2>
<p>首先，我们要明确一点：<strong>手写RTOS并不是为了造一个新轮子去替代现有的RTOS。</strong></p>
<p>成熟的开源RTOS，如FreeRTOS、RT-Thread、Zephyr，都经过了大量项目的验证。它们的功能完善、稳定性高，在实际开发产品时，我们直接使用就好，没必要用自己的。</p>
<p><strong>之所以要手写RTOS，真正的目的是：借着亲手实现的过程，把RTOS背后的工作原理吃透。</strong></p>
<p>这其实和学开车是一个道理。</p>
<blockquote>
<p>如果一个人不仅会开车，还清楚发动机、刹车系统是怎么配合工作的，甚至动手组装过一辆车，那么他开起车来往往更得心应手。</p>
</blockquote>
<p>同样的，手写RTOS追求的并不是写出一个比FreeRTOS更好的内核，而是在亲手实现每一个模块的过程中，建立起对整个系统的深刻理解。这个目标，是仅看教程、调用API实现不了的。</p>
<h2 id="学习哪些东西" tabindex="-1"><a class="header-anchor" href="#学习哪些东西"><span>学习哪些东西</span></a></h2>
<p>在手写RTOS的过程中，最值得学习的具体哪些东西呢？</p>
<p>我认为主要是以下几个核心机制。这些机制是所有RTOS普遍存的核心机制。如果能亲手实现一遍，你就真正理解了RTOS是怎么运转的。</p>
<h3 id="任务切换的机制" tabindex="-1"><a class="header-anchor" href="#任务切换的机制"><span>任务切换的机制</span></a></h3>
<p><strong>任务切换是RTOS最基础、最核心的机制</strong>。可以，说没有任务切换就没有多任务、也就没有RTOS。</p>
<p>当这部分机制时，你将从最底层的函数调用原理和汇编指令入手，一步步搞清楚很多底层问题：</p>
<blockquote>
<p>进行任务切换时，当前任务的寄存器是怎么逐个保存到它自己栈里的，下一个任务的寄存器又是怎么从它的栈里恢复回CPU的。
任务切换动作是借由哪个中断（如ARM Cortex-M上的PendSV）触发的？为什么要专门用这样一个中断？</p>
</blockquote>
<p>你可能会想：为什么要理解这些东西呢？答案是：<strong>帮助移植</strong>。</p>
<p>由于嵌入式硬件平台的多样性，你需要将RTOS移植到为自己项目设计的板子上。官方并不会给出针对该板子的移植包，所以很多工作还需要你自己来做。</p>
<p>由于任务切换是整个内核里与具体硬件关联最紧密的部分，你只有真正搞懂了切换的来龙去脉，才看得懂、也才动手改得了那部分移植代码。</p>
<h3 id="调度器的设计" tabindex="-1"><a class="header-anchor" href="#调度器的设计"><span>调度器的设计</span></a></h3>
<p>当手写调度器时，你可以理解很多很多问题：</p>
<blockquote>
<p>不同RTOS采用的调度算法，其效率差别在哪里？
抢占式调度和时间片轮转调度的具体工作方式，以及如何影响到任务的运行？</p>
</blockquote>
<p><strong>当真正理解调度器怎么工作之后，你才能把系统里任务的优先级安排得更合理。</strong> 做到真正明白任务的优先级意味着什么，任务在什么情况下会被阻塞或暂停。</p>
<h3 id="任务控制块和任务栈的设计" tabindex="-1"><a class="header-anchor" href="#任务控制块和任务栈的设计"><span>任务控制块和任务栈的设计</span></a></h3>
<p>每个任务在内核里都有一个任务控制块，用于记录优先级、状态、栈指针等信息。</p>
<p>除此之外，任务还有一个独立的栈，用来放局部变量、函数调用现场和切换时保存的上下文。</p>
<p>当手写RTOS时，你需要自己定义任务控制块的数据结构，合理安排栈的分配和大小。这能帮你解开实际开发里的很多困惑：</p>
<blockquote>
<p>栈溢出是怎么发生的？RTOS提供的栈检测到底准不准？
任务在就绪、运行、阻塞、挂起会对程序产生什么影响？
任务控制块和栈的内存是如何分配的；删除任务时，这些资源能不能被及时回收？</p>
</blockquote>
<h3 id="同步与通信机制的实现" tabindex="-1"><a class="header-anchor" href="#同步与通信机制的实现"><span>同步与通信机制的实现</span></a></h3>
<p>在实现完任务切换与调度器之后，就需要解决任务之间的同步与通信问题。</p>
<p>在手写这部分时，你会弄清楚信号量、消息队列等机制，在获取不到资源时是如何阻塞任务，条件满足时又是如何唤醒任务，任务之间的消息是如何传递的。</p>
<p>并且，这些机制有其所适用场合。<strong>只有真正理解了它们内部工作机制，你才能在具体场景里选对、用对</strong>。</p>
<h2 id="总结" tabindex="-1"><a class="header-anchor" href="#总结"><span>总结</span></a></h2>
<p>综上所述，嵌入式开发者要想真正把RTOS学透，而不是只停留在调用API层面，亲手手写一个是最有效的办法。</p>
<p>通过实现任务切换、调度器、同步与通信等核心机制，你就抓住了所有RTOS共通的东西。之后无论用哪款RTOS，还是去阅读它们的源码，你都能举一反三、快速上手。</p>
